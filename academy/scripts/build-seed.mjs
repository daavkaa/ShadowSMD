// Generates supabase/seed.sql from /content. Deterministic ids: md5(key)::uuid.
import { writeFileSync } from "node:fs";
import path from "node:path";
import { course, lessons, finalExam } from "../content/smm-foundations.mjs";
import { academies, tracks, comingSoonCourses, products } from "../content/catalog.mjs";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const lit = (s) => (s === null || s === undefined ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`;
const id = (key) => `md5(${lit(key)})::uuid`;

const out = [];
out.push("-- GENERATED by scripts/build-seed.mjs from /content. Do not edit by hand.");
out.push("-- Idempotent: safe to re-run (upserts on deterministic ids).");
out.push("begin;");

for (const a of academies) {
  out.push(`insert into public.academies (id, slug, title, description, status, sort_order) values (${id("academy:" + a.slug)}, ${lit(a.slug)}, ${lit(a.title)}, ${lit(a.description)}, ${lit(a.status)}, ${a.sort})
on conflict (id) do update set title = excluded.title, description = excluded.description, status = excluded.status, sort_order = excluded.sort_order;`);
}
for (const t of tracks) {
  out.push(`insert into public.tracks (id, academy_id, slug, title, status, sort_order) values (${id("track:" + t.slug)}, ${id("academy:" + t.academy)}, ${lit(t.slug)}, ${lit(t.title)}, ${lit(t.status)}, ${t.sort})
on conflict (id) do update set title = excluded.title, status = excluded.status, sort_order = excluded.sort_order;`);
}

const cid = id("course:" + course.slug);
out.push(`insert into public.courses (id, track_id, slug, title, summary, level, library_tier, estimated_minutes, reviewed_at, status, sort_order)
values (${cid}, ${id("track:smm-core")}, ${lit(course.slug)}, ${lit(course.title)}, ${lit(course.summary)}, ${lit(course.level)}, ${lit(course.library_tier)}, ${course.estimated_minutes}, ${lit(course.reviewed_at)}, 'published', 1)
on conflict (id) do update set title = excluded.title, summary = excluded.summary, estimated_minutes = excluded.estimated_minutes, reviewed_at = excluded.reviewed_at, status = excluded.status;`);
for (const c of comingSoonCourses) {
  out.push(`insert into public.courses (id, track_id, slug, title, summary, status, sort_order) values (${id("course:" + c.slug)}, ${id("track:" + c.track)}, ${lit(c.slug)}, ${lit(c.title)}, ${lit(c.summary)}, 'coming_soon', ${c.sort})
on conflict (id) do update set title = excluded.title, summary = excluded.summary;`);
}

out.push(`insert into public.units (id, course_id, title, sort_order) values (${id("unit:" + course.slug + ":1")}, ${cid}, 'Суурь', 1) on conflict (id) do nothing;`);

lessons.forEach((l, i) => {
  const lid = id(`lesson:${course.slug}:${l.slug}`);
  out.push(`insert into public.lessons (id, unit_id, course_id, slug, title, summary, sort_order, access_tier, estimated_minutes)
values (${lid}, ${id("unit:" + course.slug + ":1")}, ${cid}, ${lit(l.slug)}, ${lit(l.title)}, ${lit(l.summary)}, ${i + 1}, ${lit(l.access_tier)}, ${l.minutes})
on conflict (id) do update set title = excluded.title, summary = excluded.summary, sort_order = excluded.sort_order, access_tier = excluded.access_tier, estimated_minutes = excluded.estimated_minutes;`);
  if (i > 0) {
    out.push(`insert into public.learning_prerequisites (required_lesson_id, target_lesson_id) values (${id(`lesson:${course.slug}:${lessons[i - 1].slug}`)}, ${lid}) on conflict do nothing;`);
  }
  l.steps.forEach((s, j) => {
    const sid = id(`step:${course.slug}:${l.slug}:${j + 1}`);
    out.push(`insert into public.lesson_steps (id, lesson_id, kind, sort_order, points, content) values (${sid}, ${lid}, ${lit(s.kind)}, ${j + 1}, ${s.points ?? 0}, ${json(s.content)})
on conflict (id) do update set kind = excluded.kind, points = excluded.points, content = excluded.content;`);
    if (s.key) {
      out.push(`insert into public.lesson_step_keys (step_id, answer, explanation) values (${sid}, ${json(s.key)}, ${lit(s.explanation ?? "")})
on conflict (step_id) do update set answer = excluded.answer, explanation = excluded.explanation;`);
    }
  });
});

const aid = id("assessment:" + finalExam.slug);
out.push(`insert into public.assessments (id, course_id, slug, title, kind, pass_score_pct, question_count, time_limit_minutes, cooldown_hours)
values (${aid}, ${cid}, ${lit(finalExam.slug)}, ${lit(finalExam.title)}, 'final', ${finalExam.pass_score_pct}, ${finalExam.question_count}, ${finalExam.time_limit_minutes}, ${finalExam.cooldown_hours})
on conflict (id) do update set title = excluded.title, pass_score_pct = excluded.pass_score_pct, question_count = excluded.question_count, time_limit_minutes = excluded.time_limit_minutes, cooldown_hours = excluded.cooldown_hours;`);
finalExam.questions.forEach((qq, k) => {
  const qid = id(`question:${finalExam.slug}:${k + 1}`);
  out.push(`insert into public.assessment_questions (id, assessment_id, kind, topic, body) values (${qid}, ${aid}, ${lit(qq.kind)}, ${lit(qq.topic)}, ${json({ prompt: qq.prompt, options: qq.options })})
on conflict (id) do update set kind = excluded.kind, topic = excluded.topic, body = excluded.body;`);
  out.push(`insert into public.assessment_question_keys (question_id, correct, explanation) values (${qid}, ${json({ correct: qq.correct })}, ${lit(qq.explanation)})
on conflict (question_id) do update set correct = excluded.correct, explanation = excluded.explanation;`);
});

for (const p of products) {
  const pid = id("product:" + p.code);
  out.push(`insert into public.products (id, code, kind, name, description, scope_kind, audience, requires_student_verification)
values (${pid}, ${lit(p.code)}, ${lit(p.kind)}, ${lit(p.name)}, ${lit(p.description)}, ${lit(p.scope_kind)}, ${lit(p.audience ?? "b2c")}, ${p.requires_student_verification ? "true" : "false"})
on conflict (id) do update set name = excluded.name, description = excluded.description;`);
  for (const c of p.bundle_courses ?? []) {
    out.push(`insert into public.bundle_courses (bundle_product_id, course_id) values (${pid}, ${id("course:" + c)}) on conflict do nothing;`);
  }
  for (const pr of p.prices) {
    out.push(`insert into public.prices (id, product_id, code, amount_mnt, billing_interval, access_days, auto_renew, min_quantity)
values (${id("price:" + pr.code)}, ${pid}, ${lit(pr.code)}, ${pr.amount}, ${lit(pr.interval)}, ${pr.access_days ?? "null"}, false, ${pr.min_quantity ?? 1})
on conflict (id) do update set amount_mnt = excluded.amount_mnt, access_days = excluded.access_days;`);
  }
}
out.push("commit;");
writeFileSync(path.join(root, "supabase/seed.sql"), out.join("\n") + "\n");
console.log("wrote supabase/seed.sql");
